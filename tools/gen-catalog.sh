#!/usr/bin/env bash
# Regenerate skills/<app>/references/commands.md from the installed CLIs.
# Run after `craft-clis.sh update`. Needs python3. Usage: tools/gen-catalog.sh [app ...]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN_DIR="${ARTCRAFT_BIN_DIR:-$HOME/.local/bin}"

# app -> subcommand that lists its commands (JSON when the CLI can produce it)
listing() {
  case "$1" in
    photocraft|filmcraft|effectcraft|gridcraft|wordcraft|figcraft|lightcraft) echo "commands --json" ;;
    vectorcraft|designcraft|cadcraft) echo "commands" ;;
    pdfcraft) echo "tools" ;;
    deckcraft|soundcraft) echo "commands" ;;
    *) return 1 ;;
  esac
}

apps=("$@")
[[ ${#apps[@]} -gt 0 ]] || apps=(photocraft vectorcraft filmcraft effectcraft pdfcraft deckcraft gridcraft
                               wordcraft lightcraft designcraft soundcraft cadcraft figcraft)

for app in "${apps[@]}"; do
  cli="$BIN_DIR/$app-cli"
  [[ -x "$cli" ]] || { echo "skip $app: $cli not installed" >&2; continue; }
  out="$ROOT/skills/$app/references/commands.md"
  mkdir -p "$(dirname "$out")"
  tmp=$(mktemp -d)
  "$cli" --version > "$tmp/version" 2>&1 || true
  "$cli" --help > "$tmp/help" 2>&1 || "$cli" help > "$tmp/help" 2>&1 || true
  # shellcheck disable=SC2046
  "$cli" $(listing "$app") > "$tmp/list" 2>/dev/null || true
  python3 -I - "$app" "$tmp" "$out" "$(listing "$app")" <<'PY'
import json, sys, collections, pathlib
app, tmp, out, listing = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3]), sys.argv[4]
version = (tmp / "version").read_text().strip().splitlines()[0] if (tmp / "version").read_text().strip() else "?"
helptext = (tmp / "help").read_text().rstrip()
raw = (tmp / "list").read_text()
MAX = 240

def clip(s):
    s = " ".join(str(s).split())
    return s if len(s) <= MAX else s[:MAX - 1] + "…"

lines = [f"# {app}-cli command catalog", "",
         f"Generated by `tools/gen-catalog.sh` from `{version}`. Do not edit by hand.",
         f"Live, always-current source: `{app}-cli {listing}`.", "",
         "Long parameter specs are clipped here; ask the CLI for the full one (see SKILL.md).", "",
         "## `--help`", "", "```text", helptext, "```", ""]
try:
    data = json.loads(raw)
except ValueError:
    data = None

if isinstance(data, list) and data:
    groups = collections.OrderedDict()
    for c in data:
        cid = c.get("id") or c.get("name")
        if not cid:
            continue
        groups.setdefault(cid.split(".")[0].split("_")[0], []).append(c)
    lines += [f"## Commands ({sum(len(v) for v in groups.values())})", ""]
    for g, cmds in groups.items():
        lines += [f"### {g}", ""]
        for c in cmds:
            cid = c.get("id") or c.get("name")
            label = c.get("label") or c.get("description") or ""
            params = c.get("params")
            if params is None and "input_schema" in c:
                props = (c["input_schema"] or {}).get("properties", {})
                req = set((c["input_schema"] or {}).get("required", []))
                params = "{" + ", ".join(k + ("" if k in req else "?") for k in props) + "}"
            entry = f"- `{cid}` — {clip(label)}"
            if params and params != "{}":
                entry += f" — `{clip(params)}`"
            lines.append(entry)
        lines.append("")
else:
    lines += ["## Commands", "", "```text", raw.rstrip(), "```", ""]

out.write_text("\n".join(lines) + "\n")
print(f"{app}: {out.stat().st_size // 1024} KB")
PY
  rm -rf "$tmp"
done
